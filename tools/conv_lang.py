#!/usr/bin/env python3
"""Make the Russian version of a file with texts: NEMSGS.MAC + NEMSGS.ru.txt -> NEMSGSRU.MAC.

The table (UTF-8) has one pair per line, the text to find and its replacement in quotes:

    "> START GAME"   =  "> НАЧАТЬ ИГРУ"

Spaces and tabs around "=" do not matter, the spaces inside the quotes do (they count). Lines that are
empty or start with ';' are comments.

The texts of the different screens can have different translations of the same English text: the source
is divided into sections by the lines `;@ NAME` (the name in capitals), the table has the headers `[NAME]`.
A text of a section is searched in the table section with the same name first, then among the lines
before the first header (common to all). In a quoted text \\" is a quote and \\\\ is a backslash.

A text is searched as a whole string: the contents of `.ASCII /../`, `.ASCIZ /../` or of the last <..>
of the macro `MSTR`/`HSTR`. The strings with the replacement are written as bytes (the source files are
ASCII): `.BYTE 76,40,...` or, for the macros, `MSTRB`/`HSTRB` with the bytes. The codes are KOI8-R: the
font has the Latin capitals, the digits, the punctuation (ASCII 32..95) and the Cyrillic capitals
(224..255, no lowercase, no Yo). Not translated strings stay as they are.
"""
import argparse
import os
import re
import sys

SECTION = re.compile(r'^\s*\[([^\]]+)\]\s*$')
MARK = re.compile(r'^;@\s*(.*?)\s*$')
ROW = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*$')
ASCII_DIR = re.compile(r'^(\s*)(\.ASCIZ|\.ASCII)(\s+)(\S)(.*)$', re.I)
MACRO = re.compile(r'^(\s*)(MSTR|HSTR)(\s+)(.*?)<(.*)>(\s*)(;.*)?$')


def unescape(s):
    return re.sub(r'\\(.)', r'\1', s)


def read_table(path):
    table = {'': {}}
    section = ''
    with open(path, encoding='utf-8-sig') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\r\n')
            if not line.strip() or line.lstrip().startswith(';'):
                continue
            m = SECTION.match(line)
            if m:
                section = m.group(1).strip()
                if section != section.upper():
                    raise SystemExit('%s:%d: the name of a section is in capitals: [%s]' % (path, n, section.upper()))
                table.setdefault(section, {})
                continue
            m = ROW.match(line)
            if not m:
                raise SystemExit('%s:%d: expected "text" = "text" or [SECTION]' % (path, n))
            key, val = unescape(m.group(1)), unescape(m.group(2))
            rows = table[section]
            if key in rows and rows[key][0] != val:
                raise SystemExit('%s:%d: "%s" has two different translations in [%s]' % (path, n, key, section))
            rows[key] = (val, n)
    return table


def encode(text, where):
    """The bytes of the text for the font: ASCII 32..95, KOI8-R capitals 224..255."""
    out = []
    for ch in text:
        try:
            code = ch.encode('koi8_r')[0]
        except UnicodeEncodeError:
            raise SystemExit('%s: the character %r is not in KOI8-R' % (where, ch))
        if not (32 <= code <= 95 or 224 <= code <= 255) or ch == 'ё' or ch == 'Ё':
            raise SystemExit('%s: the character %r is not in the font (capitals only, no Yo)' % (where, ch))
        out.append(code)
    return out


def codes(bs):
    return ','.join('%03o' % b for b in bs)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('src', nargs='?', default='NEMSGS.MAC', help='the file with the English texts')
    ap.add_argument('-t', '--table', help='the table (default: NAME.ru.txt)')
    ap.add_argument('-o', '--output', help='the output (default: NAMERU.MAC)')
    ap.add_argument('--strict', action='store_true', help='the strings without a translation are errors')
    args = ap.parse_args()

    base, ext = os.path.splitext(args.src)
    table_path = args.table or base + '.ru.txt'
    out_path = args.output or base + 'RU' + ext
    table = read_table(table_path)
    used = set()
    sections = set([''])
    section = ''
    missing = []

    with open(args.src, encoding='ascii', newline='') as f:
        lines = f.read().replace('\r\n', '\n').split('\n')
    if lines and lines[-1] == '':
        lines.pop()

    out = ['; %s: the Russian texts of %s' % (os.path.basename(out_path), os.path.basename(args.src)),
           '; Generated by tools/conv_lang.py from %s and %s, do not edit.' % (
               os.path.basename(args.src), os.path.basename(table_path)),
           '; The codes are KOI8-R (the capitals, see NEFONT.MAC FONTR).']
    inmacro = False
    for n, line in enumerate(lines, 1):
        where = '%s:%d' % (args.src, n)
        text = None
        mk = MARK.match(line)
        if mk:
            section = mk.group(1)
            sections.add(section)
            out.append(line)
            continue
        word = line.split(None, 1)[0].upper() if line.strip() else ''
        if word == '.MACRO':
            inmacro = True
        elif word == '.ENDM':
            inmacro = False
            out.append(line)
            continue
        if inmacro:
            out.append(line)
            continue
        m = ASCII_DIR.match(line)
        if m:
            delim = m.group(4)
            e = m.group(5).find(delim)
            if e >= 0:
                text, tail = m.group(5)[:e], m.group(5)[e + 1:]
                key = text
        else:
            m2 = MACRO.match(line)
            if m2:
                text = m2.group(5)
                key = text
        if text is None or not any(ch.isalpha() for ch in text):
            out.append(line)
            continue
        hit = table.get(section, {}).get(text)
        sec = section
        if hit is None:
            hit = table[''].get(text)
            sec = ''
        if hit is None:
            missing.append((n, text))
            out.append(line)
            continue
        ru, tn = hit
        used.add((sec, text))
        bs = encode(ru, '%s:%d' % (table_path, tn))
        if m:
            zero = ',000' if m.group(2).upper() == '.ASCIZ' else ''
            rest = tail.strip()
            cmt = rest if rest.startswith(';') else ''
            out.append('%s.BYTE%s%s%s\t; %s%s' % (m.group(1), m.group(3), codes(bs), zero, text,
                                                  (' ' + cmt) if cmt else ''))
        else:
            name = m2.group(2) + 'B'
            out.append('%s%s%s%s<%s>\t; %s' % (m2.group(1), name, m2.group(3), m2.group(4), codes(bs), text))

    with open(out_path, 'w', encoding='ascii', newline='') as f:
        f.write('\n'.join(out) + '\n')

    for n, text in missing:
        print('%s:%d: no translation: "%s"' % (args.src, n, text), file=sys.stderr)
    for sec, rows in table.items():
        if sec not in sections:
            print('%s: the section [%s] is not in %s' % (table_path, sec, args.src), file=sys.stderr)
        for key, (val, tn) in rows.items():
            if (sec, key) not in used:
                print('%s:%d: the text is not used in [%s]: "%s"' % (table_path, tn, sec, key), file=sys.stderr)
    print('%s: %d strings translated, %d not translated' % (out_path, len(used), len(missing)), file=sys.stderr)
    if args.strict and missing:
        sys.exit(1)


if __name__ == '__main__':
    main()
