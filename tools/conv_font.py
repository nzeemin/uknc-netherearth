#!/usr/bin/env python3
"""Convert the Nether Earth font from the Z80 disassembly to MACRO-11 (NEFONT.MAC).

Source: netherearth-annotated-data.asm, block L6780_graphic_patterns:
64 characters (' '..'_', ASCII 32..95), 8 bytes each, one byte per pixel row.

UKNC pixel order is bit 0 = leftmost pixel, ZX is bit 7 = leftmost, so every
byte is bit-reversed (use --keep-bits to disable). Row order is kept.
"""
import argparse
import re
import sys

DEFAULT_SRC = r'D:\Work\MyProjects-old\netherearth\netherearth-disassembly-main\netherearth-annotated-data.asm'
LABEL = 'L6780_graphic_patterns'


def read_font(path):
    rows = []
    started = False
    with open(path, encoding='utf-8') as f:
        for line in f:
            s = line.split(';')[0].strip()
            if not started:
                started = line.startswith(LABEL + ':')
                continue
            if not s:
                if rows:
                    break          # blank line after data = end of block
                continue
            if re.match(r'^\w+:', s):
                break              # next label
            m = re.match(r'^db\s+(.*)$', s, re.I)
            if not m:
                raise SystemExit('unexpected line: ' + line.rstrip())
            for tok in m.group(1).split(','):
                tok = tok.strip()
                rows.append(int(tok[1:], 16) if tok.startswith('#') else int(tok, 0))
    if not started:
        raise SystemExit('label %s not found' % LABEL)
    if len(rows) % 8:
        raise SystemExit('font size %d is not a multiple of 8' % len(rows))
    return rows


def rev8(b):
    return int('{:08b}'.format(b)[::-1], 2)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('src', nargs='?', default=DEFAULT_SRC, help='Z80 disassembly data file')
    ap.add_argument('-o', '--output', default='NEFONT.MAC')
    ap.add_argument('--keep-bits', action='store_true', help='do not reverse bit order')
    args = ap.parse_args()

    data = read_font(args.src)
    if not args.keep_bits:
        data = [rev8(b) for b in data]
    nchars = len(data) // 8

    out = ['; Start of NEFONT.MAC',
           '; Generated by tools/conv_font.py from %s, do not edit.' % LABEL,
           '; %d characters from ASCII 32 (space), 8 bytes each, one byte per pixel row,' % nchars,
           '; %s.' % ('bit 0 = leftmost pixel (ZX bits reversed)' if not args.keep_bits else 'ZX bit order (bit 7 = leftmost)'),
           '',
           'FONTFC = 32.			; First character code in the font',
           'FONTCN = %d.			; Number of characters' % nchars,
           'FONTBS = FONT - <FONTFC*8.>	; Base address: FONTBS + code*8 = character bitmap',
           '']
    for i in range(nchars):
        ch = chr(32 + i)
        out.append('%s	.BYTE	%s	; %d. %s' % (
            'FONT:' if i == 0 else '',
            ','.join('%03o' % b for b in data[i * 8:i * 8 + 8]),
            32 + i, ch))
    out.append('')
    out.append('; End of NEFONT.MAC')
    with open(args.output, 'w', encoding='ascii', newline='\r\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%s: %d characters, %d bytes' % (args.output, nchars, len(data)), file=sys.stderr)


if __name__ == '__main__':
    main()
